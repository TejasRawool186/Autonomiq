"""Reporter Agent Node for Autonomiq.
Compiles analysis and source citations into a standardized Markdown report (FR-10).
"""

from datetime import datetime
from typing import Dict, Any
from backend.app.agent.state import AgentState
from backend.app.storage.file_manager import FileManager


async def reporter_node(state: AgentState) -> Dict[str, Any]:
    """Builds the comprehensive Markdown research report with verified citations."""
    title = state.get("plan", {}).get("objective") or state["objective"]
    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
    sources = state.get("raw_sources", [])
    analysis = state.get("analysis", "No detailed analysis generated.")

    sources_md = ""
    for idx, s in enumerate(sources, 1):
        url = s.get("url", "N/A")
        title_str = s.get("title", f"Source {idx}")
        sources_md += f"{idx}. **[{title_str}]({url})** — {s.get('snippet', 'No snippet available.')}\n"

    report_markdown = f"""# Autonomous Research Report: {title}

**Generated By:** Autonomiq Local-First Workspace  
**Model:** {state.get('model_name', 'gemma2:9b')}  
**Date:** {now}  
**Task ID:** `{state['task_id']}`  

---

## 1. Executive Summary

{analysis[:500]}...

---

## 2. Methodology & Evidence Retrieval

The autonomous pipeline completed:
1. Natural language objective planning.
2. Grounded web search retrieval via SerpApi.
3. Content extraction and sanitization with BeautifulSoup.
4. Semantic chunking and vector indexing in local Qdrant.
5. Local synthesis via Gemma ({state.get('model_name', 'gemma2:9b')}).

---

## 3. Detailed Findings & Synthesis

{analysis}

---

## 4. Source References & Citations

{sources_md if sources_md else "No external sources recorded."}

---

## 5. Limitations & Constraints

- Live search depends on current web indexing availability.
- Analysis synthesized strictly from collected passages and local model parameters.
- User verification recommended for critical production deployment decisions.

---
*Report generated autonomously by Autonomiq.*
"""

    # Save artifact
    path, checksum, size = FileManager.save_artifact(
        task_id=state["task_id"],
        filename="report.md",
        content=report_markdown.encode("utf-8"),
    )

    return {
        "report_markdown": report_markdown,
        "current_step": "completed",
    }
